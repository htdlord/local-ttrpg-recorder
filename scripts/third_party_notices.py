"""Write THIRD_PARTY_NOTICES.md from the installed environment.

Run after `uv sync --locked --extra gui --extra cuda` so every optional package is present:

    uv run python scripts/third_party_notices.py

It walks the runtime dependency closure of `sessionscribe` (with the `gui` and `cuda`
extras; markers are evaluated for this platform), and lists each package with its version,
licence and home page, followed by the licence files the package ships.
"""

from __future__ import annotations

import importlib.metadata as md
import platform
import re
import sys
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
EXTRAS = ("gui", "cuda")
MAX_TEXT = 20_000  # longer texts (e.g. bundled third-party notices) are referenced, not copied
LICENCE_FILE = re.compile(r"(LICEN[CS]E|COPYING|NOTICE|AUTHORS)", re.IGNORECASE)

HEADER = """\
# Third-party notices

SessionScribe's own code is MIT licensed (see [LICENSE](LICENSE)). It does not bundle
other software: `uv sync` installs the packages below from PyPI, each under its own
licence. This list is generated by `scripts/third_party_notices.py` ({platform},
Python {python}, extras: {extras}); platform-specific packages may differ elsewhere.

Notes:

- **PySide6 / Qt** (LGPLv3): installed as separate, replaceable shared libraries
  (no static linking). You may replace them with your own build of the same version.
- **NVIDIA cuBLAS and cuDNN** (`cuda` extra): installed from PyPI under NVIDIA's
  licence agreements; SessionScribe does not redistribute them.
- **Whisper model weights** are not part of SessionScribe. They are downloaded on first
  use from Hugging Face (OpenAI Whisper: MIT; check the licence of any other model you
  configure).
- **Demo audio** (`sessionscribe demo`) is downloaded from LibriVox / the Internet
  Archive (public domain); credits are written to the demo's `SOURCES.md`.
"""


def _name(dist: md.Distribution) -> str:
    return re.sub(r"[-_.]+", "-", dist.metadata["Name"]).lower()


def _licence(dist: md.Distribution) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [
        c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")
    ]
    if classifiers:
        return ", ".join(classifiers)
    text = (meta.get("License") or "").strip()
    if text and len(text) < 80 and "\n" not in text:
        return text
    return "see licence file" if text else "not stated"


def _home(dist: md.Distribution) -> str:
    meta = dist.metadata
    if meta.get("Home-page"):
        return str(meta["Home-page"])
    for url in meta.get_all("Project-URL") or []:
        label, _, link = url.partition(",")
        if label.strip().lower() in {"homepage", "home", "source", "repository", "source code"}:
            return link.strip()
    return ""


def closure(root: str = "sessionscribe", extras: tuple[str, ...] = EXTRAS) -> list[md.Distribution]:
    """Installed runtime dependencies of ``root`` (with ``extras``), sorted by name."""
    env = default_environment()
    seen: dict[str, md.Distribution] = {}
    todo: list[tuple[str, tuple[str, ...]]] = [(root, extras)]
    while todo:
        name, wanted = todo.pop()
        dist = md.distribution(name)
        key = _name(dist)
        first = key not in seen
        seen[key] = dist
        for spec in dist.requires or []:
            req = Requirement(spec)
            if req.marker is not None and not any(
                req.marker.evaluate({**env, "extra": e}) for e in ("", *wanted)
            ):
                continue
            dep = re.sub(r"[-_.]+", "-", req.name).lower()
            if dep not in seen or req.extras:
                try:
                    md.distribution(req.name)
                except md.PackageNotFoundError:
                    continue
                if first or req.extras:
                    todo.append((req.name, tuple(req.extras)))
    seen.pop(re.sub(r"[-_.]+", "-", root).lower(), None)
    return sorted(seen.values(), key=_name)


def licence_texts(dist: md.Distribution) -> list[tuple[str, str]]:
    out = []
    for file in dist.files or []:
        if LICENCE_FILE.search(file.name) and not file.name.endswith((".py", ".pyc")):
            try:
                text = file.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            out.append((str(file), text.strip()))
    return out


def render(dists: list[md.Distribution]) -> str:
    lines = [
        HEADER.format(
            platform=f"{platform.system()} {platform.machine()}",
            python=".".join(map(str, sys.version_info[:2])),
            extras=", ".join(EXTRAS),
        ),
        "| Package | Version | Licence | Home page |",
        "|---|---|---|---|",
    ]
    for d in dists:
        lines.append(f"| {d.metadata['Name']} | {d.version} | {_licence(d)} | {_home(d)} |")
    lines += ["", "## Licence texts", ""]
    shown: dict[str, str] = {}  # text -> where it was shown first
    for d in dists:
        texts = licence_texts(d)
        if not texts:
            continue
        lines.append(f"### {d.metadata['Name']} {d.version}")
        lines.append("")
        for path, text in texts:
            if len(text) > MAX_TEXT:
                lines += [
                    f"- `{path}` ({len(text) // 1024} KiB) ships with the installed package.",
                    "",
                ]
            elif text in shown:
                lines += [f"- `{path}`: same text as `{shown[text]}`.", ""]
            else:
                shown[text] = path
                lines += [f"<details><summary>{path}</summary>", "", "```text", text, "```", ""]
                lines += ["</details>", ""]
    text = "\n".join(lines).replace("\r\n", "\n")
    return "\n".join(line.rstrip() for line in text.split("\n")).rstrip() + "\n"


def main() -> None:
    dists = closure()
    OUT.write_text(render(dists), encoding="utf-8", newline="\n")
    print(f"{OUT.name}: {len(dists)} packages, {OUT.stat().st_size // 1024} KiB")


if __name__ == "__main__":
    main()
